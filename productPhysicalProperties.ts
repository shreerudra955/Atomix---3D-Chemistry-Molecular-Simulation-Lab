function buildFallbackPhysicalProperties(p: ReactionParticipant): ProductPhysicalProperties {
  const colorName = p.appearance
    ? p.appearance.split(/[;(]/)[0].trim()
    : p.state === 'g'
    ? 'Colorless'
    : p.state === 's'
    ? 'Solid Crystalline'
    : 'Clear Colorless';

  if (p.state === 's') {
    return {
      physicalStateLabel: 'Solid Phase',
      colorName,
      odor: 'Odorless',
      meltingPointC: 'High-melting Ionic / Metallic Lattice',
      boilingPointC: 'High / Decomposes',
      density: 'Solid (> 1.5 g/cm³)',
      solubilityInWater: 'Insoluble / Precipitated Solid',
      textureOrForm: p.appearance || 'Solid Precipitate / Deposit',
      conductivityOrMagnetism: 'Solid Phase',
    };
  }
  if (p.state === 'g') {
    return {
      physicalStateLabel: 'Gaseous Phase',
      colorName,
      odor: p.formula.includes('SO') || p.formula.includes('NH') || p.formula.includes('Cl')
        ? 'Pungent / Sharp'
        : 'Odorless',
      meltingPointC: 'Cryogenic (< -50 °C)',
      boilingPointC: 'Sub-ambient (< 20 °C)',
      density: `${(p.molarMassGPerMol / 24.465).toFixed(2)} g/L (at 25 °C, 1 atm)`,
      solubilityInWater: 'Low to Moderate Gas Solubility',
      textureOrForm: p.appearance || 'Evolving Gas Bubbles / Headspace Vapor',
      conductivityOrMagnetism: 'Non-Conductive Gas Phase',
    };
  }
  if (p.state === 'l') {
    return {
      physicalStateLabel: 'Pure Liquid Phase',
      colorName,
      odor: 'Odorless',
      meltingPointC: '0.0 °C',
      boilingPointC: '100.0 °C',
      density: '1.00 g/mL',
      solubilityInWater: 'Miscible Liquid',
      textureOrForm: p.appearance || 'Liquid Phase',
      conductivityOrMagnetism: 'Molecular Liquid',
    };
  }
  return {
    physicalStateLabel: 'Aqueous Solution (aq)',
    colorName,
    odor: 'Odorless',
    meltingPointC: '~0 °C (Aqueous Solution)',
    boilingPointC: '~100–102 °C (Aqueous Solution)',
    density: '~1.02–1.05 g/mL (Aqueous)',
    solubilityInWater: 'Dissolved Homogeneous Aqueous Ions / Solute',
    textureOrForm: p.appearance || 'Dissolved Aqueous Species',
    conductivityOrMagnetism: 'Aqueous Electrolyte / Solute',
  };
}

export function enrichParticipantPhysicalProperties(
  participant: ReactionParticipant
): ReactionParticipant {
  if (participant.physicalProperties) {
    return participant;
  }
  const key = normalizeFormulaKey(participant.formula, participant.state);
  const catalogMatch = PRODUCT_PHYSICAL_CATALOG[key];
  return {
    ...participant,
    physicalProperties: catalogMatch ?? buildFallbackPhysicalProperties(participant),
  };
}
