const SUBSCRIPT_TO_ASCII: Record<string, string> = {
  '₀': '0',
  '₁': '1',
  '₂': '2',
  '₃': '3',
  '₄': '4',
  '₅': '5',
  '₆': '6',
  '₇': '7',
  '₈': '8',
  '₉': '9',
  '⁰': '0',
  '¹': '1',
  '²': '2',
  '³': '3',
  '⁴': '4',
  '⁵': '5',
  '⁶': '6',
  '⁷': '7',
  '⁸': '8',
  '⁹': '9',
};

function normalizeFormulaKey(formula: string, state: string): string {
  let clean = formula
    .replace(/\(aq\)|\(s\/aq\)|\(s\)|\(l\/g\)|\(l\)|\(g\)|↓|↑/g, '')
    .trim();

  clean = clean
    .split('')
    .map((ch) => SUBSCRIPT_TO_ASCII[ch] ?? ch)
    .join('');

  // Strip leading stoichiometric coefficient (e.g. "2Ag" -> "Ag", "2HCl" -> "HCl", "2H2O" -> "H2O")
  clean = clean.replace(/^\d+/, '').trim();

  // Distinguish species that exist in multiple states (e.g. I2(g) vs I2(aq), H2O(g) vs H2O(l))
  if (clean === 'I2' && state === 'g') return 'I2_g';
  if (clean === 'I2' && state === 'aq') return 'I2_aq';
  if (clean === 'H2O' && state === 'g') return 'H2O_g';
  if (clean === 'HCl' && state === 'g') return 'HCl_g';
  if (clean === 'Ca(OH)2' && formula.includes('s')) return 'Ca(OH)2_s';

  return clean;
}

