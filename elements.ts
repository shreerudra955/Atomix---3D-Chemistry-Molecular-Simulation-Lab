// Helper to look up an element by atomic number or symbol
export function getElement(key: number | string): ElementData | undefined {
  if (typeof key === 'number') {
    return ELEMENTS.find((el) => el.atomicNumber === key);
  }
  const clean = key.trim().toLowerCase();
  return ELEMENTS.find(
    (el) => el.symbol.toLowerCase() === clean || el.name.toLowerCase() === clean
  );
}

